    /**
     * Варианты фраз для описаний машин: ключ → список вариантов (по строке на вариант).
     *
     * @return array<string, list<string>>
     */
    public static function carTexts(): array
    {
        return array_map(
            fn ($text) => array_values(array_filter(array_map('trim', preg_split('/\R/u', (string) $text) ?: []))),
            self::group('seo_car_texts'),
        );
    }

    /** Варианты фраз как в админке: строка с вариантами через перенос. @return array<string, string> */
    public static function carTextsRaw(): array
    {
        return self::group('seo_car_texts');
    }

    /** Один вариант фразы, стабильный для конкретной машины (seed — например, id). */
    public static function pick(string $key, int|string $seed): ?string
    {
        $variants = self::carTexts()[$key] ?? [];
        if ($variants === []) {
            return null;
        }

        return $variants[crc32($key.'|'.$seed) % count($variants)];
    }

    /** @return array<string, array<string, string>> */
    public static function templates(): array
    {
        $stored = (array) Setting::get('seo_templates', []);
        $result = self::DEFAULTS['seo_templates'];
        foreach ($stored as $type => $fields) {
            foreach ((array) $fields as $field => $value) {
                if ($value !== null && $value !== '') {
                    $result[$type][$field] = $value;
                }
            }
        }

        return $result;
    }

    /**
     * Готовый текст по шаблону: meta('brand', 'title', ['name' => 'Kia', 'price' => 1700]).
     * Незаполненные подстановки и двойные пробелы убираются.
     */
    public static function meta(string $type, string $field, array $vars = []): string
    {
        $template = (string) (self::templates()[$type][$field] ?? '');

        return self::fill($template, $vars);
    }

    public static function fill(string $template, array $vars = []): string
    {
        if ($template === '') {
            return '';
        }

        $general = self::general();
        $vars += ['site' => $general['site_name'], 'sep' => $general['title_separator']];
        if (isset($vars['name'])) {
            $vars['name_lower'] = mb_strtolower((string) $vars['name']);
        }

        if (isset($vars['price']) && is_numeric($vars['price'])) {
            $vars['price'] = number_format((float) $vars['price'], 0, ',', ' ');
        }

        $text = preg_replace_callback('/\{(\w+)\}/u', fn ($m) => (string) ($vars[$m[1]] ?? ''), $template);

        // «от  ₽/сутки» без цены выглядит сломанным — такие куски убираем
        $text = preg_replace(['/\s*—\s*от\s+₽\/сутки/u', '/\s*от\s+₽\/сутки/u', '/\s{2,}/u'], ['', '', ' '], (string) $text);

        return trim((string) $text);
    }

    /** Заголовок для N-й страницы пагинации: суффикс вставляется перед « | Сайт». */
    public static function paginate(string $title, int $page): string
    {
        if ($page <= 1) {
            return $title;
        }

        $general = self::general();
        $suffix = self::fill((string) $general['pagination_suffix'], ['page' => $page]);
        $tail = $general['title_separator'].$general['site_name'];

        return str_ends_with($title, $tail)
            ? substr($title, 0, -strlen($tail)).' '.ltrim($suffix).$tail
            : $title.' '.ltrim($suffix);
    }

    public static function flush(): void
    {
        self::$memo = [];
    }

    /** @return array<string, mixed> */
    private static function group(string $key): array
    {
        if (isset(self::$memo[$key])) {
            return self::$memo[$key];
        }

        $result = self::DEFAULTS[$key];
        foreach ((array) Setting::get($key, []) as $field => $value) {
            if ($value !== null && $value !== '') {
                $result[$field] = $value;
            }
        }

        return self::$memo[$key] = $result;
    }
