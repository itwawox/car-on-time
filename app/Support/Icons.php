    /** @var array<string, true> */
    private static array $used = [];

    public static function brand(string $name, int $size): string
    {
        if (! isset(self::BRANDS[$name])) {
            return '';
        }
        self::$used['b:'.$name] = true;

        return '<svg width="'.$size.'" height="'.$size.'" viewBox="'.self::BRANDS[$name][0].'" fill="currentColor" aria-hidden="true" focusable="false"><use href="#b-'.$name.'"/></svg>';
    }

    public static function use(string $name): string
    {
        if (! isset(self::PATHS[$name])) {
            return '';
        }
        self::$used[$name] = true;

        return '<use href="#i-'.$name.'"/>';
    }

    /** Спрайт в конце страницы — только иконки, которые встретились в разметке. */
    public static function sprite(): string
    {
        if (! self::$used) {
            return '';
        }
        $symbols = '';
        foreach (array_keys(self::$used) as $name) {
            if (str_starts_with($name, 'b:')) {
                [$viewBox, $paths] = self::BRANDS[substr($name, 2)];
                $symbols .= '<symbol id="b-'.substr($name, 2).'" viewBox="'.$viewBox.'">'.$paths.'</symbol>';
            } else {
                $symbols .= '<symbol id="i-'.$name.'" viewBox="0 0 24 24">'.self::PATHS[$name].'</symbol>';
            }
        }
        self::$used = [];

        return '<svg xmlns="http://www.w3.org/2000/svg" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">'.$symbols.'</svg>';
    }
